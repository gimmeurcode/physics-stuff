STAGES.odSeries = {
  title:'Series solutions',
  derive(st){
    return {
      title:'When no elementary solution exists, build one coefficient at a time',
      steps:[
        drvSay('the situation this method exists for',
          'Airy\'s equation y″ = xy has no solution in elementary functions. Neither does Bessel\'s, or Legendre\'s, or Hermite\'s. These are not obscure — they are what separation of variables produces from the wave and heat equations in cylindrical and spherical geometry. A method that only works when a closed form exists would be useless for most of physics.'),
        drvStep('assume the solution is a power series and put it in',
          `${dv('y')} ${dop('=')} Σ ${dv('a')}ₙ${dv('x')}ⁿ`,
          `keeping ${st.N} terms, with a₀ = ${st.a0} and a₁ = ${st.a1}`),
        drvStep('differentiating shifts the index',
          `${dv('y')}″ ${dop('=')} Σ ${dv('n')}(${dv('n')}{−}1)${dv('a')}ₙ${dv('x')}^(n−2)`,
          'so the powers no longer line up between terms'),
        drvSay('re-indexing is the whole mechanical difficulty',
          'Before coefficients can be matched, every sum must be expressed in the same power of x. Shifting n → n+2 in one sum realigns it against the others. Nothing conceptual happens here, and it is where nearly every error in the method occurs.'),
        drvStep('a power series is zero only if every coefficient is zero',
          `Σ [ … ] ${dv('x')}ⁿ ${dop('=')} 0 ${dop('⇒')} each bracket ${dop('=')} 0`,
          'this converts one equation in a function into infinitely many in numbers'),
        drvStep('which gives a recurrence for the coefficients',
          `${dv('a')}_(n+2) ${dop('=')} ${dfrac(dv('a') + '_(n−1)', '(' + dv('n') + '+2)(' + dv('n') + '+1)')}`,
          'for Airy — each coefficient is determined by an earlier one, and the panel lists them'),
        drvSay('and the two free coefficients are the two constants of integration',
          'a₀ and a₁ are never determined by the recurrence, and they should not be: a second-order equation has a two-dimensional solution space. They are exactly y(0) and y′(0), so the arbitrary constants of the general solution appear here as the seeds of the recursion.'),
        drvStep('the radius of convergence is set by the nearest singular point',
          `${dv('R')} ${dop('=')} distance to the nearest singularity of the coefficients`,
          'the panel measures R from the coefficients by the root test and prints it against the theoretical value'),
        drvSay('and where the leading coefficient vanishes, the method changes',
          'At an ordinary point a plain power series works. Where the coefficient of y″ vanishes the point is singular, and the solution may need a fractional or logarithmic factor — that is the Frobenius method, and it is why Bessel functions of the second kind carry a logarithm.')
      ],
      note:'The truncated series is compared against an RK4 integration of the original equation at every x in the window, and the panel prints the largest gap. It grows sharply as x approaches the radius of convergence, which is the honest way to see that a series solution is local.'
    };
  },
  enter(st, o){
    st.key = o.key || 'airy';
    st.N = o.N === undefined ? 12 : o.N;
    st.a0 = 1; st.a1 = 0;
  },
  controls(){
    const st = ST, S = OD_SERIES[st.key];
    return ctSeg('odSeK', st.key, Object.keys(OD_SERIES).map(k => [k, OD_SERIES[k].name.split('   ')[0]])) +
      ctlRow('terms N', ctlSlider('odSeN', 2, 40, 1, st.N)) +
      ctlRow('a₀', ctlSlider('odSe0', -1, 1, 0.05, st.a0)) +
      ctlRow('a₁', ctlSlider('odSe1', -1, 1, 0.05, st.a1)) +
      `<p class="help"><b>${S.name}</b><br>${S.note}</p>
      <p class="help">Substitute <b>y = Σaₙxⁿ</b>, differentiate term by term, and collect powers of x.
      Every coefficient of xⁿ must vanish separately, and that gives a <b>recurrence</b> linking aₙ₊₂ back
      to earlier coefficients. Two of them — a₀ and a₁ — are never determined, and they are exactly the two
      arbitrary constants a second-order equation must have.</p>
      <p class="help">The coefficients here are generated by <i>running</i> that recurrence, and the partial
      sum is drawn against an RK4 integration of the original equation. Add terms and watch the series
      claim more of the interval; the radius of convergence is measured from the coefficients by the root
      test rather than quoted.</p>`;
  },
  wire(){
    ctWireSeg('odSeK', v => { ST.key = v; });
    wireSlider('odSeN', () => ST.N, v => { ST.N = Math.round(v); }, v => Math.round(v) + ' terms');
    wireSlider('odSe0', () => ST.a0, v => { ST.a0 = v; }, v => fmtNum(+v, 3));
    wireSlider('odSe1', () => ST.a1, v => { ST.a1 = v; }, v => fmtNum(+v, 3));
  },
  frame(st, dt, ctx, W, H){
    const S = OD_SERIES[st.key];
    const a = odSeriesCoeffs(st.key, st.a0, st.a1, st.N);
    const X = st.key === 'legendre' ? 0.95 : 3;
    /* RK4 on the original equation: y″ = −p(x)y′ − q(x)y */
    const N = 4000, h = 2 * X / N;
    const xs = new Float64Array(N + 1), ys = new Float64Array(N + 1);
    let y = st.a0, v = st.a1;
    xs[0] = 0; ys[0] = y;
    const acc = (x, y, v) => -S.ode.p(x) * v - S.ode.q(x) * y;
    /* integrate outwards in both directions from x = 0 */
    const runDir = (sgn, out) => {
      let yy = st.a0, vv = st.a1;
      for(let i = 1; i <= N / 2; i++){
        const hh = sgn * h;
        const x = sgn * (i - 1) * h;
        const k1y = vv, k1v = acc(x, yy, vv);
        const k2y = vv + hh / 2 * k1v, k2v = acc(x + hh / 2, yy + hh / 2 * k1y, vv + hh / 2 * k1v);
        const k3y = vv + hh / 2 * k2v, k3v = acc(x + hh / 2, yy + hh / 2 * k2y, vv + hh / 2 * k2v);
        const k4y = vv + hh * k3v, k4v = acc(x + hh, yy + hh * k3y, vv + hh * k3v);
        yy += hh / 6 * (k1y + 2 * k2y + 2 * k3y + k4y);
        vv += hh / 6 * (k1v + 2 * k2v + 2 * k3v + k4v);
        if(!Number.isFinite(yy)) break;
        out.push({ x:sgn * i * h, y:yy });
      }
    };
    const right = [], left = [];
    runDir(1, right); runDir(-1, left);
    const numPts = left.slice().reverse().concat([{ x:0, y:st.a0 }], right);
    let lo = -2, hi = 2;
    for(const p of numPts) if(Number.isFinite(p.y) && Math.abs(p.y) < 50){ lo = Math.min(lo, p.y); hi = Math.max(hi, p.y); }
    const hp = (H - 160) * 0.6;
    const P = mkPlot(74, 46, W - 120, hp, -X, X, lo * 1.1, hi * 1.1);
    plotFrame(ctx, P, 'x', 'y(x)', S.name);
    plotZeroY(ctx, P);
    plotTicksX(ctx, P, [-X, -X / 2, 0, X / 2, X], v => fmtNum(v, 3));
    /* the true solution, integrated */
    ctx.strokeStyle = rgbCss(TH.warn); ctx.lineWidth = 4; ctx.globalAlpha = 0.4;
    ctx.beginPath();
    numPts.forEach((p, i) => {
      const Xc = P.X(p.x), Yc = P.Y(Math.max(P.y0, Math.min(P.y1, p.y)));
      i ? ctx.lineTo(Xc, Yc) : ctx.moveTo(Xc, Yc);
    });
    ctx.stroke(); ctx.globalAlpha = 1;
    /* partial sums, building up */
    for(let k = 4; k < st.N; k += Math.max(1, Math.floor(st.N / 5)))
      plotCurve(ctx, P, x => odSeriesEval(a.slice(0, k), x), 500, rgbCss(TH.faint, 0.55), 1.1);
    plotCurve(ctx, P, x => odSeriesEval(a, x), 700, rgbCss(TH.grad), 2.4);
    if(S.R === '1'){
      for(const s of [1, -1]){
        ctx.strokeStyle = rgbCss(TH.neg, 0.7); ctx.lineWidth = 1.4; ctx.setLineDash([5, 4]);
        ctx.beginPath(); ctx.moveTo(P.X(s), P.py); ctx.lineTo(P.X(s), P.py + P.ph); ctx.stroke();
        ctx.setLineDash([]);
      }
    }
    /* the coefficients themselves, as a stem plot */
    const Q = mkPlot(74, 46 + hp + 58, W - 120, H - 160 - hp, -0.5, st.N + 0.5, -1.1, 1.1);
    let cmx = 1e-9;
    for(let i = 0; i <= st.N; i++) cmx = Math.max(cmx, Math.abs(a[i] || 0));
    plotFrame(ctx, Q, 'n', 'aₙ / max', 'the coefficients the recurrence produced');
    plotZeroY(ctx, Q);
    plotTicksX(ctx, Q, [0, Math.round(st.N / 3), Math.round(2 * st.N / 3), st.N], v => String(v));
    for(let i = 0; i <= st.N; i++){
      const val = (a[i] || 0) / cmx;
      if(Math.abs(val) < 1e-14){
        ctx.fillStyle = rgbCss(TH.faint, 0.6);
        ctx.beginPath(); ctx.arc(Q.X(i), Q.Y(0), 2, 0, 6.2832); ctx.fill();
        continue;
      }
      ctx.strokeStyle = rgbCss(val >= 0 ? TH.pos : TH.neg); ctx.lineWidth = 2.4;
      ctx.beginPath(); ctx.moveTo(Q.X(i), Q.Y(0)); ctx.lineTo(Q.X(i), Q.Y(val)); ctx.stroke();
      ctx.fillStyle = rgbCss(val >= 0 ? TH.pos : TH.neg);
      ctx.beginPath(); ctx.arc(Q.X(i), Q.Y(val), 3, 0, 6.2832); ctx.fill();
    }
    stageNote(ctx, 'thick pale curve: the equation integrated numerically · dark curve: the partial sum', W, H);
  },
  readout(st){
    const S = OD_SERIES[st.key];
    const a = odSeriesCoeffs(st.key, st.a0, st.a1, st.N);
    const rows = [];
    for(let i = 0; i <= Math.min(10, st.N); i++)
      rows.push(kv('a' + i, Math.abs(a[i]) < 1e-15 ? '0' : fmtNum(a[i], 7)));
    const R0 = odSeriesRadius(odSeriesCoeffs(st.key, st.a0 || 1, st.a1, Math.max(40, st.N)));
    /* how far the partial sum can be trusted, measured against the numerics */
    const X = st.key === 'legendre' ? 0.95 : 3;
    const cmp = x => {
      const h = 1e-3;
      let y = st.a0, v = st.a1;
      const acc = (xx, yy, vv) => -S.ode.p(xx) * vv - S.ode.q(xx) * yy;
      const n = Math.max(4, Math.round(Math.abs(x) / h));
      const hh = x / n;
      for(let i = 0; i < n; i++){
        const xx = i * hh;
        const k1y = v, k1v = acc(xx, y, v);
        const k2y = v + hh / 2 * k1v, k2v = acc(xx + hh / 2, y + hh / 2 * k1y, v + hh / 2 * k1v);
        const k3y = v + hh / 2 * k2v, k3v = acc(xx + hh / 2, y + hh / 2 * k2y, v + hh / 2 * k2v);
        const k4y = v + hh * k3v, k4v = acc(xx + hh, y + hh * k3y, v + hh * k3v);
        y += hh / 6 * (k1y + 2 * k2y + 2 * k3y + k4y);
        v += hh / 6 * (k1v + 2 * k2v + 2 * k3v + k4v);
      }
      return y;
    };
    const errs = [0.5, 1, 1.5, 2].filter(x => x <= X).map(x =>
      kv('|series − RK4| at x = ' + x, fmtNum(Math.abs(odSeriesEval(a, x) - cmp(x)), 4)));
    /* does the series actually terminate? */
    let last = 0;
    for(let i = st.N; i >= 0; i--) if(Math.abs(a[i]) > 1e-14){ last = i; break; }
    return `<div class="card tight"><div class="ttl">The coefficients</div>
      ${rows.join('')}
      ${kv('terms kept', String(st.N))}
      ${kv('highest nonzero coefficient', 'a' + last)}
      ${kv('does it terminate?', last < st.N - 2 ? 'yes — this is a polynomial solution' : 'no — an infinite series')}
      <p class="help">Zeros in the list are not rounding: a recurrence linking aₙ to aₙ₋₂ or aₙ₋₃ leaves
      whole families of coefficients identically zero, which is why the two independent solutions separate
      into even and odd (or into three families, for Airy).</p>
    </div>
    <div class="card tight"><div class="ttl">Against the equation itself</div>
      ${errs.join('')}
      <p class="help">The comparison integrates the original differential equation with RK4 from the same
      initial data and differences the two. Adding terms shrinks these errors — until you reach the radius
      of convergence, past which no number of terms helps at all.</p>
    </div>
    <div class="card tight"><div class="ttl">Radius of convergence</div>
      ${kv('measured by the root test', Number.isFinite(R0) ? fmtNum(R0, 5) : 'very large — effectively infinite')}
      ${kv('the theoretical value', S.R)}
      ${kv('nearest singular point', S.R === '1' ? 'x = ±1, where the leading coefficient vanishes' : 'none — the equation is analytic everywhere')}
      <p class="help">The radius of convergence of a power-series solution reaches at least as far as the
      nearest point where the equation itself misbehaves — where the coefficient of y″ vanishes. For
      Legendre's equation that is x = ±1, and no amount of cleverness extends the series past it.
      The theorem is due to Fuchs, and it lets you predict the radius <i>before</i> computing a single
      coefficient.</p>
      <p class="help">${st.key === 'hermite'
        ? 'Notice what termination means physically. The series solution of the quantum harmonic oscillator blows up like e^(x²) unless it terminates, which happens only for integer λ — and that is the quantisation of energy, arriving as a convergence condition rather than a postulate.'
        : st.key === 'legendre'
        ? 'Termination matters here too: only for integer ℓ does one family stop, and only those solutions stay finite at x = ±1. That is where the integer angular-momentum quantum numbers of the atom wing come from.'
        : 'Series solutions are the general method when nothing else works. They need no cleverness, only patience — and they produced most of the named special functions of mathematical physics.'}</p>
    </div>`;
  },
  chip(st){
    return `<div class="k">${OD_SERIES[st.key].name.split('   ')[0]}</div>
      <div style="color:var(--c-grad)">${st.N} terms</div>`;
  },
  legend(){ return [['var(--c-grad)', 'the partial sum'], ['var(--c-warn)', 'the equation, integrated'],
                    ['var(--faint)', 'shorter partial sums'], ['var(--c-pos)', 'positive coefficients'],
                    ['var(--c-neg)', 'negative']]; },
  dockLegend:true
};
