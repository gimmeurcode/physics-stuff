/* ============================================================================
   3f-k · A NETLIST, AND WHAT IT TAKES TO DRAW ONE

   The bench already lets a reader build any circuit, one click at a time. What
   it does not let them do is *write* one down — and a netlist is how circuits
   are actually exchanged, stored, and generated by anything other than a hand.
   Four lines describe a filter that takes a minute to lay out with the mouse,
   and the four lines can be pasted into a message.

   The format is SPICE's, cut down to what this bench models:

       * a comment
       V1 in 0 SIN(5 1k)
       R1 in out 1k
       C1 out 0 100n

   name, then its nodes, then its value. The first letter of the name chooses
   the part, which is the convention every SPICE deck in existence follows.
   Node names are arbitrary words; `0` and `gnd` are ground.

   THE PART THAT IS NOT PARSING

   The bench is geometric. It stores components at grid coordinates and wires
   between them, and it recovers the netlist from that geometry — two points are
   one node when they touch, and crossing wires that share no endpoint are not
   connected, exactly as on paper. So a netlist cannot simply be handed to the
   solver: it has to be *placed*, and placed in a way that cannot accidentally
   connect two things the text did not connect.

   The layout used here is the one that makes that guarantee easy to keep:

     · every node becomes a vertical rail, at x = 8·(its index);
     · every component gets a row of its own, three units below the last;
     · the component sits at x ≡ 3 (mod 8), so neither it nor its pins — which
       are one or two units either side — can ever land on a rail;
     · each lead is one horizontal wire from a pin to its rail.

   A lead crossing rails it does not belong to is drawn crossing them, and
   crossing is not connection. That is not a stylistic choice: it is the reason
   the layout is safe for any netlist at all, however tangled, without a routing
   algorithm and without ever needing to check whether a placement went wrong.
   ============================================================================ */

/* which part a designator's first letter means, following SPICE */
const CK_NET_KIND = { R:'R', C:'C', L:'L', V:'V', I:'I', D:'D', S:'SW',
                      U:'OPAMP', X:'OPAMP', K:'M' };
const CK_NET_NP = { R:2, C:2, L:2, V:2, I:2, D:2, SW:2, OPAMP:3, M:0 };

/* `SIN(5 1k)` is one token to a human and three to a splitter, so the argument
   list is normalised before splitting: brackets and commas become spaces, and
   the function name is left as a word of its own. */
function ckNetTokens(line){
  return line.replace(/[(),]/g, ' ').trim().split(/\s+/).filter(s => s.length);
}
/* a number in engineering shorthand, or NaN */
function ckNetNum(tok){
  if(tok === undefined) return NaN;
  const v = ckParseEng(tok);
  return Number.isFinite(v) ? v : NaN;
}

/* ---------------------------------------------------------------------------
   The parser. It never throws: every complaint is collected with the line it
   came from, because a reader who has mistyped one line wants to be told which
   line and what was wrong with it, not handed a blank board.
   --------------------------------------------------------------------------- */
function ckParseNetlist(text){
  const errs = [], parts = [], nodeOrder = [];
  const lines = String(text == null ? '' : text).split(/\r?\n/);
  const nodeId = name => {
    const n = String(name).toLowerCase();
    const g = (n === '0' || n === 'gnd' || n === 'ground') ? '0' : n;
    if(nodeOrder.indexOf(g) < 0) nodeOrder.push(g);
    return g;
  };
  nodeId('0');                                     /* ground is always index 0 */

  for(let li = 0; li < lines.length; li++){
    const raw = lines[li];
    const bare = raw.replace(/[;#].*$/, '').trim();
    if(!bare || bare[0] === '*') continue;
    const tk = ckNetTokens(bare);
    const name = tk[0];
    const kind = CK_NET_KIND[name[0].toUpperCase()];
    if(!kind){
      errs.push({ line:li + 1, msg:'"' + name + '" — the first letter must name a part: ' +
        'R C L V I D S (switch) U (op amp) K (coupling)' });
      continue;
    }
    if(parts.some(p => p.name.toLowerCase() === name.toLowerCase())){
      errs.push({ line:li + 1, msg:'"' + name + '" is used twice — every part needs its own name' });
      continue;
    }
    const np = CK_NET_NP[kind];
    const args = tk.slice(1 + np);
    if(kind === 'M'){
      /* K1 L1 L2 0.5 — no pins of its own, just two inductors and a number */
      const k = ckNetNum(tk[3]);
      if(tk.length < 4 || !Number.isFinite(k)){
        errs.push({ line:li + 1, msg:'a coupling needs two inductor names and a coefficient, e.g. K1 L1 L2 0.5' });
        continue;
      }
      parts.push({ kind, name, nodes:[], over:{ a:tk[1], b:tk[2], k:Math.max(-1, Math.min(1, k)) }, line:li + 1 });
      continue;
    }
    if(tk.length < 1 + np){
      errs.push({ line:li + 1, msg:'"' + name + '" needs ' + np + ' node' + (np === 1 ? '' : 's') +
        ' after its name' + (kind === 'OPAMP' ? ' — the + input, the − input, then the output' : '') });
      continue;
    }
    const nodes = tk.slice(1, 1 + np).map(nodeId);
    if(np === 2 && nodes[0] === nodes[1]){
      errs.push({ line:li + 1, msg:'"' + name + '" has both ends on node ' + tk[1] +
        ', which shorts it out — a part between one node and itself does nothing' });
      continue;
    }
    const over = {};
    let bad = null;

    /* ---- the passive values ---- */
    if(kind === 'R' || kind === 'C' || kind === 'L'){
      const v = ckNetNum(args[0]);
      if(!Number.isFinite(v) || v <= 0)
        bad = 'expected a positive value, e.g. 1k, 4k7, 100n, 2.2M — got "' + (args[0] === undefined ? '(nothing)' : args[0]) + '"';
      else over.val = v;
    }
    /* ---- diodes and switches ---- */
    if(kind === 'D'){ over.is = 1e-14; over.nn = 1; }
    if(kind === 'SW'){
      over.closed = args.some(a => /^closed$/i.test(a));
      over.mode = 'manual';
    }
    /* ---- sources ---- */
    if(kind === 'V' || kind === 'I'){
      const w = (args[0] || '').toLowerCase();
      const num0 = ckNetNum(args[0]);
      if(Number.isFinite(num0)){ over.wave = 'dc'; over.val = num0; }
      else if(w === 'dc'){
        const v = ckNetNum(args[1]);
        if(!Number.isFinite(v)) bad = 'DC needs a value, e.g. DC 12';
        else { over.wave = 'dc'; over.val = v; }
      }
      else if(w === 'sin' || w === 'ac' || w === 'square' || w === 'tri' || w === 'saw' ||
              w === 'pulse' || w === 'ring' || w === 'chirp' || w === 'noise'){
        const A = ckNetNum(args[1]), f = ckNetNum(args[2]);
        if(!Number.isFinite(A)) bad = w.toUpperCase() + ' needs an amplitude, e.g. ' + w.toUpperCase() + '(5 1k)';
        else {
          over.wave = (w === 'ac') ? 'sin' : w;
          over.amp = A;
          over.freq = Number.isFinite(f) ? Math.max(1e-9, f) : 1e3;
          const off = ckNetNum(args[3]);
          if(Number.isFinite(off)) over.off = off;
        }
      }
      else if(w === 'step' || w === 'exp'){
        const A = ckNetNum(args[1]);
        if(!Number.isFinite(A)) bad = w.toUpperCase() + ' needs an amplitude';
        else { over.wave = w; over.amp = A;
               const p = ckNetNum(args[2]); if(Number.isFinite(p)){ if(w === 'exp') over.tau = p; else over.t0 = p; } }
      }
      else bad = 'a source takes a number, or DC v, or one of SIN SQUARE TRI SAW PULSE STEP EXP RING CHIRP NOISE — got "' +
                 (args[0] === undefined ? '(nothing)' : args[0]) + '"';
    }
    /* ---- named options, for anything that has them: IC=, ESR=, RON= ---- */
    for(const a of args){
      const m = /^([A-Za-z]+)=(.+)$/.exec(a);
      if(!m) continue;
      const key = m[1].toUpperCase(), v = ckNetNum(m[2]);
      if(!Number.isFinite(v)){ bad = bad || (m[1] + '= needs a number'); continue; }
      if(key === 'IC') over.ic = v;
      else if(key === 'ESR') over.esr = v;
      else if(key === 'RON') over.ron = v;
      else if(key === 'IS') over.is = v;
      else if(key === 'N') over.nn = v;
      else if(key === 'VSAT') over.vsat = v;
      else bad = bad || ('unknown option "' + m[1] + '="');
    }
    if(bad){ errs.push({ line:li + 1, msg:'"' + name + '" — ' + bad }); continue; }
    parts.push({ kind, name, nodes, over, line:li + 1 });
  }

  /* a coupling whose inductors do not exist is a silent no-op in the solver, so
     it is caught here instead */
  for(const p of parts) if(p.kind === 'M'){
    for(const which of ['a', 'b'])
      if(!parts.some(q => q.kind === 'L' && q.name.toLowerCase() === String(p.over[which]).toLowerCase()))
        errs.push({ line:p.line, msg:'"' + p.name + '" couples "' + p.over[which] + '", which is not an inductor in this netlist' });
  }
  const real = parts.filter(p => p.kind !== 'M');
  if(!real.length && !errs.length) errs.push({ line:0, msg:'nothing to build — write at least one part' });
  if(real.length && !real.some(p => p.nodes.indexOf('0') >= 0))
    errs.push({ line:0, msg:'no part touches node 0 — every circuit needs a ground reference, and node 0 is it' });
  /* A node with only one pin on it carries no current and makes the matrix
     singular. The solver would say so, but it would say so about a node number
     rather than about the word that was typed, so it is caught here. */
  const deg = new Map();
  for(const p of real) for(const n of p.nodes) deg.set(n, (deg.get(n) || 0) + 1);
  for(const [n, d] of deg) if(d < 2 && n !== '0')
    errs.push({ line:0, msg:'node "' + n + '" has only one thing attached to it, so no current can flow through it — ' +
      'either connect something else there, or the part is meant to reach a node you have spelled differently' });

  return { ok:errs.length === 0, parts, errs, nodes:nodeOrder,
           sch:errs.length === 0 ? ckLayoutNetlist(parts, nodeOrder) : null };
}

/* ---------------------------------------------------------------------------
   Placement. See the header: node rails on multiples of 8, one row per part,
   bodies at x ≡ 3 (mod 8) so nothing can land on a rail by accident.
   --------------------------------------------------------------------------- */
function ckLayoutNetlist(parts, nodeOrder){
  const RAIL = 8, ROW = 3;
  const X = name => nodeOrder.indexOf(name) * RAIL;
  const comps = [], wires = [];
  const real = parts.filter(p => p.kind !== 'M');
  const bottom = -ROW * real.length - 2;
  /* the rails, one vertical wire each, clear of every row at both ends */
  for(const n of nodeOrder) wires.push({ a:{ x:X(n), y:2 }, b:{ x:X(n), y:bottom } });
  comps.push({ kind:'GND', name:'G1', x:0, y:bottom });

  let row = 0;
  for(const p of parts){
    if(p.kind === 'M'){
      comps.push(Object.assign({ kind:'M', name:p.name, x:-10, y:-ROW * row }, p.over));
      continue;
    }
    const y = -ROW * row++;
    const xs = p.nodes.map(X);
    const mid = xs.reduce((a, b) => a + b, 0) / xs.length;
    const cx = Math.floor(mid / RAIL) * RAIL + 3;
    comps.push(Object.assign({ kind:p.kind, name:p.name, x:cx, y }, p.over));
    if(p.kind === 'OPAMP'){
      /* in+ at (cx−2, y−1), in− at (cx−2, y+1), out at (cx+2, y) */
      wires.push({ a:{ x:cx - 2, y:y - 1 }, b:{ x:xs[0], y:y - 1 } });
      wires.push({ a:{ x:cx - 2, y:y + 1 }, b:{ x:xs[1], y:y + 1 } });
      wires.push({ a:{ x:cx + 2, y }, b:{ x:xs[2], y } });
    } else {
      /* Pin 0 belongs to the first node named, and for a source that is its +
         terminal — so which side of the body pin 0 sits on is not free. It is
         fixed by rotating the part, and the rotation is chosen so that each lead
         leaves its own pin *away* from the body.

         Getting this wrong does not produce a crooked picture, it produces a
         wrong circuit: a lead that has to double back reaches its node by
         running straight over the part's other pin, and a wire passing through a
         pin is a connection. That shorted every part whose nodes happened to be
         named right-to-left, and the ten-resistor chain in the unit suite is
         there to keep it shorted-out if it ever comes back. */
      const rot = xs[0] <= xs[1] ? 0 : 180;
      comps[comps.length - 1].rot = rot;
      const p0 = rot === 0 ? cx - 1 : cx + 1;
      const p1 = rot === 0 ? cx + 1 : cx - 1;
      wires.push({ a:{ x:p0, y }, b:{ x:xs[0], y } });
      wires.push({ a:{ x:p1, y }, b:{ x:xs[1], y } });
    }
  }
  return ckNewSch(comps, wires);
}

/* ---------------------------------------------------------------------------
   And the other direction: read the board back out as text. This is what makes
   the format learnable — build something with the mouse, look at the netlist it
   produced, edit the text. The node numbers come from the same geometry pass the
   solver uses, so what is printed is genuinely the circuit being solved rather
   than a second opinion about it.
   --------------------------------------------------------------------------- */
/* engineering notation with no space in it, so a value survives being split on
   whitespace and read back by ckParseEng — six figures, because three would
   quietly round 1 234 Ω to 1.23 k on the way out and back */
const ckNetEng = v => ckEng(v, '', 6).replace(/\s+/g, '');
function ckNetlistText(sch){
  const nm = ckNodeMap(sch);
  const out = ['* read from the board — node 0 is ground'];
  const nodeOf = p => { const n = nm.node(p); return n < 0 ? '?' : String(n); };
  for(const c of sch.comps){
    if(c.kind === 'GND') continue;
    if(c.kind === 'M'){ out.push([c.name, c.a, c.b, String(c.k)].join(' ')); continue; }
    const pins = ckPins(c);
    if(c.kind === 'OPAMP'){ out.push([c.name, nodeOf(pins[0]), nodeOf(pins[1]), nodeOf(pins[2])].join(' ')); continue; }
    if(pins.length < 2) continue;
    /* ckPins has already applied the rotation, so pins[0] is pin 0 wherever it
       physically ended up — and pin 0 is the node named first, which for a source
       is its + terminal. No further swap: adding one here inverted every source
       that had been rotated, and the round-trip test caught it by the sign of a
       current rather than by anything visible. */
    const a = nodeOf(pins[0]), b = nodeOf(pins[1]);
    let val = '';
    if(c.kind === 'R' || c.kind === 'C' || c.kind === 'L') val = ckNetEng(c.val);
    else if(c.kind === 'V' || c.kind === 'I')
      val = c.wave === 'dc' ? ckNetEng(c.val)
          : c.wave.toUpperCase() + '(' + ckNetEng(c.amp) + ' ' + ckNetEng(c.freq) + ')';
    else if(c.kind === 'SW') val = c.closed ? 'CLOSED' : 'OPEN';
    const extra = [];
    if((c.kind === 'C' || c.kind === 'L') && c.ic) extra.push('IC=' + ckNetEng(c.ic));
    if(c.kind === 'L' && c.esr) extra.push('ESR=' + ckNetEng(c.esr));
    out.push([c.name, a, b, val].concat(extra).join(' ').trim());
  }
  return out.join('\n');
}
